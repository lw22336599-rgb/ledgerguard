import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const registryDir = join(root, "registry", "extensions");
const manifests = readdirSync(registryDir)
  .filter((name) => name.endsWith(".json"))
  .sort()
  .map((name) => JSON.parse(readFileSync(join(registryDir, name), "utf8")));

if (manifests.length === 0) throw new Error("Extension registry cannot be empty");
const revocations = JSON.parse(
  readFileSync(join(root, "registry", "revocations.json"), "utf8"),
);
if (
  revocations.schemaVersion !== "ledgerguard.extension-revocations.v1" ||
  !Array.isArray(revocations.revocations)
) {
  throw new Error("Invalid extension revocations registry");
}
const output = `// Generated from registry/extensions/*.json and registry/revocations.json by scripts/build-extension-registry.mjs.\n// Do not edit this file by hand.\nexport const generatedExtensionManifests = ${JSON.stringify(manifests, null, 2)} as const;\nexport const generatedExtensionRevocations = ${JSON.stringify(revocations.revocations, null, 2)} as const;\n`;
writeFileSync(join(root, "src", "extensions", "generated-registry.ts"), output);
console.log(`Generated ${manifests.length} extension manifest(s).`);
